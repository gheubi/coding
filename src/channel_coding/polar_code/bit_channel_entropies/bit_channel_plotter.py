def h2(p):
    p = np.clip(p, 1e-12, 1 - 1e-12)
    return -(p * np.log2(p) + (1 - p) * np.log2(1 - p))
 
def mutual_information(p, sigma, s0, s1):
    #function generated by chatGPT
    px0 = 1 - p
    px1 = p

    print(f"With p(X=1)={p}, sigma={sigma}, (0, 1) -> ({s0}, {s1})")

    log_px0 = np.log(px0)
    log_px1 = np.log(px1)

    def log_py_x(y, mean):
        return norm.logpdf(y, mean, sigma)

    def integrand(y, mean):
        log_pyx = log_py_x(y, mean)

        log_py = logsumexp([
            log_px0 + log_py_x(y, s0),
            log_px1 + log_py_x(y, s1)
        ])

        return np.exp(log_pyx) * (log_pyx - log_py) / np.log(2)

    L0 = s0 - 10*sigma
    R0 = s0 + 10*sigma
    L1 = s1 - 10*sigma
    R1 = s1 + 10*sigma

    I0, _ = quad(
        lambda y: integrand(y, s0),
        L0, R0,
        epsabs=1e-12,
        epsrel=1e-12
    )

    I1, _ = quad(
        lambda y: integrand(y, s1),
        L1, R1,
        epsabs=1e-12,
        epsrel=1e-12
    )

    return px0*I0 + px1*I1

