def get_entropies_for_id(sid):
    df = pd.read_csv(data_path)
    df = df[(df["id"] == sid)]
    indexes_and_ent = zip(df["index"], df["value"])
    res = [-1 for i in range(0, len(df))]
    for i, v in indexes_and_ent:
        res[int(i) - 1] = v
    for r in res:
        if r == -1:
            raise Exception(f"Inconsitent data in {indexes_and_ent}")
    return res
