def get_avg(rs, ds):
    #generated by chatGPT
    values = defaultdict(list)

    for r, d in zip(rs, ds):
        values[r].append(d)

    rs_avg = list(values.keys())
    ds_avg = [sum(values[r]) / len(values[r]) for r in rs_avg]

    return rs_avg, ds_avg

