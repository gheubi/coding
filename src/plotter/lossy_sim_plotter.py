def h2(p):
    p = np.clip(p, 1e-12, 1 - 1e-12)
    return -(p * np.log2(p) + (1 - p) * np.log2(1 - p))

def get_rate_distortion_bound():
    ds = [i/128 for i in range(0,65)]
    rs = [1 - h2(d) for d in ds]
    return rs, ds

