def get_point_for_id(pid):
    df = pd.read_csv(path_data)
    df = df[(df.id == pid)]
    row = df.iloc[0]

    return row["rate"], row["observed_distortion"]

def create_dic(s:str) -> dict:
    s = "code=" + s
    s = s.replace(' ', '')
    ls = []
    for f in s.split(')'):
        for part in f.split('('):
            for ppart in f.split(';'):
                ls.append(ppart)
    ls[0] = ls[0].split('(')[1]
    ls[-1] = ls[-1].strip(')')
    return dict(item.split('=') for item in ls if len(item.split('=')) == 2)


