ϕ(y, μ, σ) = exp(-(y-μ)^2 / (2σ^2)) / sqrt(2π*σ^2)

function fy(y, p, σ)
    μ = 1 / sqrt(p)
    return (1-p)*ϕ(y, 0.0, σ) + p*ϕ(y, μ, σ)
end

function hY(p, σ)
    integrand(y) = begin
        f = fy(y, p, σ)
        -f * log2(f)
    end
    μ = 1 / sqrt(p)
    L = maximum([10σ, μ + 10σ])
    val, _ = quadgk(integrand, -L, L)
    return val
end

#=
    Compute the mutual information of an OOK constellation with a given probability p of transmitting a 1 and a given noise standard deviation sigma.
    The mutual information is computed as the difference between the entropy of the output and the conditional entropy of the output given the input.
    The function uses numerical integration to compute the entropy of the output.
    @param p the probability of transmitting a 1
    @param sigma the standard deviation of the noise
    @return the mutual information in bits  
=#
function mutual_information(p, σ)
    h_cond = 0.5 * log2(2π * exp(1) * σ^2)
    return hY(p, σ) - h_cond
end

#=
    Returns, for a given sigma ≥ 0, the p* that achieves the capacity of the 
    AWGNC with an OOK constellation of unit power.
=#
function opt_ook(sigma)
    0 <= sigma || ERROR(UTILS_OOK_OPTIM_TAG, "$sigma must be positive")
    σ = sigma
    objective(p) = -mutual_information(p, σ)
    res = optimize(objective, 1e-5, 1-1e-5)
    p_opt = Optim.minimizer(res)
    I_opt = -Optim.minimum(res)
    return p_opt, I_opt
end