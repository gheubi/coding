gauss(y, μ, σ) = exp(-0.5*((y-μ)/σ)^2)/(sqrt(2π)*σ)
#=
    Compute the conditional entropy H(Y|X) of an OOK constellation with a given probability p of transmitting a 1 and a given noise standard deviation sigma.
    The conditional entropy is computed as the expected value of the entropy of the output given the input.
    The function uses numerical integration to compute the conditional entropy.
    The signal is assumed to be transmitted with an average power of 1, i.e., the transmitted symbols are 0 and 1/sqrt(p).
    @param p the probability of transmitting a 1
    @param sigma the standard deviation of the noise
    @return the conditional entropy H(Y|X)
=#
#generated by chatGPT
function conditional_entropy_ook(p1, σ)
    σ == 0 && return 0.0
    c1 = 1/sqrt(p1)
    function posterior(y,p,c,σ)
        L = log(p/(1-p)) + (2c*y - c^2)/(2σ^2)
        if L > 40
            return 1.0
        elseif L < -40
            return 0.0
        else
            return inv(1 + exp(-L))
        end
    end
    function integrand(y)
        f0 = (1-p1)*gauss(y,0,σ)
        f1 = p1*gauss(y,c1,σ)
        py = f0 + f1
        post = posterior(y,p1,c1,σ)
        return py*h2(post)
    end
    val, _ = quadgk(integrand, -Inf, Inf, rtol=1e-10)
    return val
end

mutual_information_ook(p1, sigma) = h2(p1) - conditional_entropy_ook(p1, sigma)