#=
    Compute the binary entropy function h2(p) = -p*log2(p) - (1-p)*log2(1-p)
    for a given probability p in [0, 1].
    The function returns 0 for p = 0 or p = 1.
    @param p the probability value
    @return the binary entropy h2(p)
=#
h2(p::REAL) = begin
    0 <= p <= 1 || ERROR(UTILS_ENTROPY_TAG, "$p is not a valid probability")
    (p == 0 || p == 1) && return 0.0
    return -p*log2(p) - (1-p)*log2(1-p)
end

#=
    Compute the inverse of the binary entropy function h2(p) for a given entropy value h in [0, 1].
    The function returns the probability p in [0, 0.5] such that h2(p) = h.
    @param h the entropy value
    @return the probability p such that h2(p) = h
=#
h2_inv(h::REAL) = begin
    0 <= h <= 1 || ERROR(UTILS_ENTROPY_TAG, "$h is not a valid binary entropy")

    h == 1 && return 0.5
    h == 0 && return 0.0

    f(p) = h2(p) - h
    return find_zero(p -> f(p), (0.0, 0.5), Bisection())
end

#=
    Compute the entropy of a discrete probability distribution represented by a vector of probabilities ps.
    The function returns the entropy H(ps) = -sum(p*log2(p)) for all p in ps.
    The input vector ps must sum to 1 and contain valid probabilities in [0, 1].
    @param ps the vector of probabilities
    @return the entropy H(ps)
=#
H(ps::Vector{REAL}) = begin
    all(0 .<= ps .<= 1) || ERROR(UTILS_ENTROPY_TAG, "$ps contains invalid probabilities")
    sum(ps) == 1 || ERROR(UTILS_ENTROPY_TAG, "$ps does not form a valid distribution")
    acc = 0
    @inbounds for p in ps
        acc += p*log2(p)
    end
    return -acc
end

#=
    Compute the Kullback-Leibler divergence D_KL(p || q) between two binary distributions with probabilities p and q.
=#
KL_div(p::REAL, q::REAL) = begin
    0 <= p <= 1 || ERROR(UTILS_ENTROPY_TAG, "$p is not a valid probability")
    0 <= q <= 1 || ERROR(UTILS_ENTROPY_TAG, "$q is not a valid probability")

    acc = p*(log2(p) - log2(q))
    acc += (1-p)*(log2(1-p) - log2(1-q))
    return acc
end

#=
    Compute the Kullback-Leibler divergence D_KL(p || q) between two discrete probability distributions p and q represented by vectors of probabilities.
    The function returns the KL divergence D_KL(p || q) = sum(p*log2(p/q)) for all corresponding probabilities in p and q.
    The input vectors p and q must have the same length, sum to 1, and contain valid probabilities in [0, 1].
    @param p the first probability distribution
    @param q the second probability distribution
    @return the KL divergence D_KL(p || q)
=#
KL_div(ps::Vector{REAL}, qs::Vector{REAL}) = begin
    all(0 .<= ps .<= 1) || ERROR(UTILS_ENTROPY_TAG, "$ps contains invalid probabilities")
    all(0 .<= qs .<= 1) || ERROR(UTILS_ENTROPY_TAG, "$qs contains invalid probabilities")
    sum(ps) == 1 || ERROR(UTILS_ENTROPY_TAG, "$ps does not form a valid distribution")
    sum(qs) == 1 || ERROR(UTILS_ENTROPY_TAG, "$qs does not form a valid distribution")
    length(ps) == length(qs) || ERROR(UTILS_ENTROPY_TAG, "first and second probability distributions don't have the same support")

    acc = 0
    @inbounds for i in eachindex(ps)
        acc += ps[i]*(log2(ps[i]) - log2(qs[i]))
    end
    return acc
end

